def recommend_for_customer(customer_id, k=5):
    customer_id = str(customer_id)
    if customer_id not in users:                       # cold start -> popularity
        print("Unknown customer -> showing most popular products")
        top = np.argsort(-pop_full)[:k]
        return pd.DataFrame({"Recommended product": [item_names[i] for i in top]})
    u = users.get_loc(customer_id)
    bought = R_full[u].indices
    s = np.asarray(R_full[u] @ S_full).ravel(); s[bought] = -np.inf
    top = np.argsort(-s)[:k]
    print(f"Customer {customer_id} | previously bought {len(bought)} products, e.g.:")
    for i in bought[:5]: print("   -", item_names[i])
    return pd.DataFrame({"Recommended product": [item_names[i] for i in top],
                         "Score": np.round(s[top], 3)})

def recommend_for_basket(stock_codes, k=5):
    idx = [items.get_loc(c) for c in stock_codes if c in items]
    s = S_full[idx].sum(axis=0); s[idx] = -np.inf
    top = np.argsort(-s)[:k]
    return pd.DataFrame({"Recommended product": [item_names[i] for i in top], "Score": np.round(s[top], 3)})

