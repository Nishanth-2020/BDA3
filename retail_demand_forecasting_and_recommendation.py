"""## 5. Demand forecasting
**Task:** predict next week's units sold for each of the top-N products.

**Features (no data leakage - only past information):** lag 1-4 weeks, rolling mean/std (4 & 8 weeks), last week's order count, price, price change, week-of-year, month, and a product-level mean demand computed from the training period only.

**Models:** two naive baselines (last week, 4-week moving average) vs Linear Regression, Random Forest and Gradient Boosting. Evaluation uses a **time-based split** (last `TEST_WEEKS` weeks = test set).
"""

