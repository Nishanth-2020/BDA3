basket = basket[basket.sum(axis=1) >= 2]
print(f"Basket matrix: {basket.shape[0]:,} orders x {basket.shape[1]} items")

def mine_rules(basket, supports=(0.02, 0.015, 0.01, 0.007, 0.005), min_rules=15):
    for s in supports:
        freq = fpgrowth(basket, min_support=s, use_colnames=True)
        if len(freq) == 0:
            continue
        try:
            rules = association_rules(freq, metric="lift", min_threshold=1.2)
        except TypeError:
            rules = association_rules(freq, num_itemsets=len(basket), metric="lift", min_threshold=1.2)
        rules = rules[rules["confidence"] >= 0.2]
        if len(rules) >= min_rules:
            break
    return s, freq, rules

min_sup, freq_items, rules = mine_rules(basket)
nm = lambda fs: ", ".join(name_map[i][:28] for i in sorted(fs))
