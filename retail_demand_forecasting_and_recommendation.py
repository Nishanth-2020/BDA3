def load_uci_online_retail():
    urls = [
        "https://archive.ics.uci.edu/static/public/352/online+retail.zip",
        "https://archive.ics.uci.edu/ml/machine-learning-databases/00352/Online%20Retail.xlsx",
    ]
    for u in urls:
        try:
            r = requests.get(u, timeout=90)
            r.raise_for_status()
            if u.endswith(".zip"):
                z = zipfile.ZipFile(io.BytesIO(r.content))
                name = [n for n in z.namelist() if n.lower().endswith(".xlsx")][0]
                return pd.read_excel(z.open(name))
            return pd.read_excel(io.BytesIO(r.content))
        except Exception as e:
            print(f"Download failed for {u}: {type(e).__name__}")
    return None


def make_synthetic_retail(seed=42, n_customers=1500, n_products=120,
                          start="2023-01-01", end="2024-12-31"):
    """Synthetic retail transactions with the UCI Online Retail schema."""
    rng = np.random.default_rng(seed)
    cats = ["Home Decor", "Kitchen", "Stationery", "Toys", "Garden", "Gifts", "Bath"]
    cat_of = rng.integers(0, len(cats), n_products)
    price = np.round(rng.lognormal(1.0, 0.6, n_products) + 0.5, 2)
    codes = [f"P{1000 + i}" for i in range(n_products)]
    names = [f"{cats[c].upper()} ITEM {i + 1}" for i, c in enumerate(cat_of)]
    pop = rng.pareto(1.3, n_products) + 1
    pop = pop / pop.sum()
    bundles = [rng.choice(n_products, 3, replace=False) for _ in range(12)]  # co-purchased sets
    pref = [rng.choice(len(cats), 2, replace=False) for _ in range(n_customers)]
    aff = np.ones((n_customers, n_products))
    for c in range(n_customers):
        aff[c, np.isin(cat_of, pref[c])] = 4.0
    month_mult = np.ones((13, n_products))
    for m in range(1, 13):
        for ci, cn in enumerate(cats):
            f = 1.0
            if cn in ("Toys", "Gifts") and m in (11, 12): f = 2.5
            if cn == "Garden" and m in (4, 5, 6, 7): f = 2.0
            if cn == "Home Decor" and m in (10, 11, 12): f = 1.5
            if cn == "Bath" and m in (1, 2): f = 1.4
            month_mult[m, cat_of == ci] = f

    t0 = pd.Timestamp(start)
    rows, inv_no = [], 500000
    for d in pd.date_range(start, end):
        base = (22 * (1 + 0.5 * (d.month in (11, 12))) * (0.45 if d.weekday() == 5 else 1.0)
                * (1 + 0.0004 * (d - t0).days))
        for _ in range(rng.poisson(base)):
            c = int(rng.integers(n_customers))
            w = pop * aff[c] * month_mult[d.month]
            w = w / w.sum()
            if rng.random() < 0.35:
                items = set(bundles[int(rng.integers(len(bundles)))].tolist())
                items |= set(rng.choice(n_products, int(rng.integers(0, 3)), replace=False, p=w).tolist())
            else:
                items = set(rng.choice(n_products, int(rng.integers(2, 8)), replace=False, p=w).tolist())
            ts = d + pd.Timedelta(hours=int(rng.integers(8, 19)), minutes=int(rng.integers(0, 60)))
            inv_no += 1
            for it in items:
                rows.append((str(inv_no), codes[it], names[it], int(rng.poisson(3)) + 1,
                             ts, float(price[it]), float(c + 10000), "United Kingdom"))

    df = pd.DataFrame(rows, columns=["InvoiceNo", "StockCode", "Description", "Quantity",
                                     "InvoiceDate", "UnitPrice", "CustomerID", "Country"])
    # ---- inject dirty data so the cleaning step is meaningful ----
    n = len(df)
    df.loc[rng.random(n) < 0.04, "CustomerID"] = np.nan                       # missing customers
    df.loc[rng.random(n) < 0.002, "Description"] = np.nan                     # missing descriptions
    df.loc[rng.random(n) < 0.003, "UnitPrice"] = 0.0                          # invalid prices
    mask = rng.random(n) < 0.01                                               # inconsistent text
    df.loc[mask, "Description"] = df.loc[mask, "Description"].str.lower() + " "
    canc = df.sample(frac=0.015, random_state=seed).copy()                    # cancellations
    canc["InvoiceNo"] = "C" + canc["InvoiceNo"]
    canc["Quantity"] = -canc["Quantity"]
    post = df.sample(200, random_state=seed).copy()                           # non-product rows
    post["StockCode"], post["Description"] = "POST", "POSTAGE"
    df = pd.concat([df, df.sample(frac=0.01, random_state=seed), canc, post], ignore_index=True)  # duplicates too
    return df.sample(frac=1, random_state=seed).sort_values("InvoiceDate").reset_index(drop=True)


