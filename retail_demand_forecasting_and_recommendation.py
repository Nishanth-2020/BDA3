"""## 7. Recommender system
**Data:** customer x product implicit-feedback matrix (1 = bought). Customers with >= 5 distinct products and products with >= 5 buyers are kept.

**Split:** for every customer, 20 % of purchased products are hidden as the test set. Models must predict these hidden products from the remaining 80 %.

**Models:** Popularity (baseline), Item-based Collaborative Filtering (cosine), User-based CF (top-50 neighbours), Matrix factorisation (Truncated SVD).

**Metrics @K:** Precision, Recall, Hit-rate, NDCG, and catalogue Coverage.
"""

cust = df.dropna(subset=["CustomerID"])[["CustomerID", "StockCode"]].drop_duplicates()
for _ in range(3):  # iterative filtering
    cust = cust[cust.groupby("CustomerID")["StockCode"].transform("nunique") >= 5]
    cust = cust[cust.groupby("StockCode")["CustomerID"].transform("nunique") >= 5]

users = pd.Index(sorted(cust["CustomerID"].unique())); items = pd.Index(sorted(cust["StockCode"].unique()))
cust = cust.assign(u=users.get_indexer(cust["CustomerID"]), i=items.get_indexer(cust["StockCode"]))

cust = cust.sample(frac=1, random_state=SEED)
cust["rank"] = cust.groupby("u").cumcount()
cust["n"] = cust.groupby("u")["u"].transform("size")
cust["is_test"] = cust["rank"] < np.maximum(1, (0.2 * cust["n"]).round())

n_users, n_items = len(users), len(items)
mk = lambda d: sparse.csr_matrix((np.ones(len(d), dtype=np.float32), (d["u"], d["i"])), shape=(n_users, n_items))
R_train, R_test, R_full = mk(cust[~cust["is_test"]]), mk(cust[cust["is_test"]]), mk(cust)
density = R_full.nnz / (n_users * n_items)
print(f"Users: {n_users:,} | Items: {n_items:,} | Interactions: {R_full.nnz:,} | Density: {density:.2%}")
print(f"Train interactions: {R_train.nnz:,} | Test interactions: {R_test.nnz:,}")

def top_k_users(k_neighbors, S):
    """Keep only the k strongest neighbours per row of a similarity matrix."""
    S = S.copy()
    idx = np.argpartition(-S, k_neighbors, axis=1)[:, k_neighbors:]
    np.put_along_axis(S, idx, 0, axis=1)
    return S

def score_popularity(R):
    return np.tile(np.asarray(R.sum(axis=0)).ravel(), (R.shape[0], 1)).astype(np.float32)

def item_similarity(R):
    S = cosine_similarity(R.T.tocsr()); np.fill_diagonal(S, 0); return S

def score_item_cf(R):
    return np.asarray(R @ item_similarity(R))

def score_user_cf(R, neighbours=50):
    S = cosine_similarity(R); np.fill_diagonal(S, 0)
    S = top_k_users(min(neighbours, S.shape[0] - 1), S)
    return np.asarray(S @ R)

def score_svd(R, factors=40):
    svd = TruncatedSVD(n_components=factors, random_state=SEED)
    Z = svd.fit_transform(R)
    return Z @ svd.components_

def evaluate_recs(scores, R_train, R_test, k=10):
    sc = np.array(scores, dtype=np.float32)
    r, c = R_train.nonzero(); sc[r, c] = -np.inf                       # never recommend already-bought items
    topk = np.argpartition(-sc, k, axis=1)[:, :k]
    order = np.argsort(-np.take_along_axis(sc, topk, axis=1), axis=1)
    topk = np.take_along_axis(topk, order, axis=1)
    test_dense = R_test.toarray() > 0
    hits = np.take_along_axis(test_dense, topk, axis=1)
    n_rel = test_dense.sum(axis=1)
    disc = 1 / np.log2(np.arange(2, k + 2))
    dcg = (hits * disc).sum(axis=1)
    idcg = np.array([disc[:min(n, k)].sum() for n in n_rel])
    valid = n_rel > 0
    return {f"Precision@{k}": (hits.sum(1) / k)[valid].mean(),
            f"Recall@{k}": (hits.sum(1) / np.maximum(n_rel, 1))[valid].mean(),
            f"HitRate@{k}": hits.any(axis=1)[valid].mean(),
            f"NDCG@{k}": (dcg / np.maximum(idcg, 1e-9))[valid].mean(),
            "Coverage": len(np.unique(topk)) / R_train.shape[1]}

rec_models = {"Popularity (baseline)": score_popularity, "Item-based CF": score_item_cf,
              "User-based CF": score_user_cf, "SVD (matrix factorisation)": score_svd}
rec_results = pd.DataFrame({n: evaluate_recs(f(R_train), R_train, R_test, K) for n, f in rec_models.items()}).T
print(f"Recommendation performance (K={K}) on hidden purchases")
rec_results.round(4).sort_values(f"NDCG@{K}", ascending=False)

