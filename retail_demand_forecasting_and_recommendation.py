"""## 6. Pattern mining - frequently purchased product combinations
We build an order x product basket matrix (top items only), run **FP-Growth** to find frequent itemsets, and derive **association rules** measured by *support*, *confidence* and *lift* (lift > 1 means products are bought together more often than by chance).
"""

item_orders = df.groupby("StockCode")["InvoiceNo"].nunique().nlargest(TOP_ITEMS_MINING).index
bk = df[df["StockCode"].isin(item_orders)][["InvoiceNo", "StockCode"]].drop_duplicates()
